                        <h2>ขอบเขตของนโยบายความเป็นส่วนตัว</h2>
                    </div>
                    <p>
                        สำนักวิทยบริการ มหาวิทยาลัยสงขลานครินทร์ วิทยาเขตปัตตานี (“หน่วยงาน”) ให้ความสำคัญกับการคุ้มครองข้อมูลส่วนบุคคลของท่านตามพระราชบัญญัติคุ้มครองข้อมูลส่วนบุคคล พ.ศ. 2562 (PDPA)
                        นโยบายฉบับนี้อธิบายถึงวิธีการเก็บรวบรวม ใช้ เปิดเผย และคุ้มครองข้อมูลส่วนบุคคลของท่านเมื่อใช้งานเว็บไซต์ <strong>OAR Shopping (shopping.oas.psu.ac.th)</strong>
                    </p>
                </div>

                <div class="oar-privacy-card" id="collect">
                    <div class="oar-privacy-card-head">
                        <span class="oar-privacy-num">02</span>
                        <h2>ข้อมูลส่วนบุคคลที่เราเก็บรวบรวม</h2>
                    </div>
                    <p>เราเก็บรวบรวมข้อมูลส่วนบุคคลเท่าที่จำเป็นต่อการให้บริการสั่งซื้อสินค้า ดังนี้:</p>
                    <ul class="oar-privacy-list">
                        <li>
                            <strong>ข้อมูลบัญชีและการยืนยันตัวตน:</strong>
                            ชื่อ–นามสกุล, ชื่อที่แสดง (Display Name), อีเมล, เบอร์โทรศัพท์ และรหัสอ้างอิงผู้ใช้จากการสมัครสมาชิกหรือการเข้าสู่ระบบผ่าน PSU Passport, Google และ LINE
                        </li>
                        <li>
                            <strong>ข้อมูลการสั่งซื้อและการจัดส่งสินค้า:</strong>
                            ชื่อผู้รับ, ที่อยู่จัดส่ง, หมายเลขโทรศัพท์, รายการสินค้าที่สั่งซื้อ, ข้อมูลสำหรับออกใบเสร็จรับเงิน และหลักฐานการโอนเงิน/ชำระเงิน
                        </li>
                        <li>
                            <strong>ข้อมูลการติดต่อสื่อสาร:</strong>
                            ข้อความและข้อมูลที่ท่านส่งเข้ามาผ่านหน้า “ติดต่อเรา” เพื่อขอความช่วยเหลือหรือสอบถามสถานะคำสั่งซื้อ
                        </li>
                        <li>
                            <strong>ข้อมูลทางเทคนิคและคุกกี้ที่จำเป็น:</strong>
                            คุกกี้เซสชัน (Session Cookies) สำหรับคงสถานะการเข้าสู่ระบบและรายการสินค้าในตะกร้าของท่าน
                        </li>
                    </ul>
