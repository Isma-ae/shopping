                        <li>เพื่อดำเนินการรับคำสั่งซื้อ ตรวจสอบหลักฐานการชำระเงิน ออกใบเสร็จรับเงิน และจัดส่งสินค้าให้ถึงผู้รับอย่างถูกต้อง</li>
                        <li>เพื่อแจ้งสถานะคำสั่งซื้อ เลขพัสดุ และให้บริการหลังการขายหรือการเปลี่ยนคืนสินค้า</li>
                        <li>เพื่อป้องกันการใช้งานโดยมิชอบและปฏิบัติตามข้อกำหนดทางกฎหมายหรือระเบียบของมหาวิทยาลัย</li>
